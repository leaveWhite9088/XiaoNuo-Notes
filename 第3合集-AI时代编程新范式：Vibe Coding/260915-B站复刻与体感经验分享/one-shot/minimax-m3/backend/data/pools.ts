export function pickTags(categoryName: string, rng: () => number): string[] {
  const pool = TAG_POOLS[categoryName] ?? TAG_POOLS.综合
  const n = 2 + Math.floor(rng() * 3)
  const picked: string[] = []
  const used = new Set<number>()
  while (picked.length < n) {
    const i = Math.floor(rng() * pool.length)
    if (used.has(i)) continue
    used.add(i)
    picked.push(pool[i])
  }
  return picked
}
